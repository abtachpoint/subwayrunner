#!/usr/bin/env python3
"""Import original Kenney CC0 GLB geometry into the offline WebGL mesh format.
Source ZIPs remain external; generated asset may be regenerated from exact archives.
No runtime network requests or texture servers needed.
"""
import base64, io, json, math, re, struct, sys, zipfile
from pathlib import Path
import numpy as np
import trimesh
from PIL import Image

ARCHIVES = [
 ('commercial','kenney_city-kit-commercial_2.1.zip'),
 ('suburban','kenney_city-kit-suburban_20.zip'),
 ('train','kenney_train-kit.zip'),
]
PACK = struct.Struct('<3h3h4B')
ROOT=Path(__file__).resolve().parents[1]; DOWNLOAD=Path(sys.argv[1]) if len(sys.argv)>1 else ROOT
output=ROOT/'web/assets/kenney_models.js'
models={}; categories={}; errors=[]; count=0
for category, archive in ARCHIVES:
    with zipfile.ZipFile(DOWNLOAD/archive) as z:
        entries=sorted(x for x in z.namelist() if x.startswith('Models/GLB format/') and x.endswith('.glb'))
        palette_file=next((x for x in z.namelist() if x=='Models/GLB format/Textures/colormap.png'),None)
        pal=np.asarray(Image.open(io.BytesIO(z.read(palette_file))).convert('RGB')) if palette_file else None
        print(category,len(entries),'palette',None if pal is None else pal.shape,flush=True)
        keys=[]
        for path in entries:
            name=Path(path).stem; key=category+':'+name
            try:
                scene=trimesh.load(io.BytesIO(z.read(path)),file_type='glb',force='scene')
                raw=bytearray(); mins=np.array([1e8,1e8,1e8]);maxs=-mins;total_tri=0
                # Geometry transforms are obtained from each graph node.
                for node in scene.graph.nodes_geometry:
                    matrix, geom_name=scene.graph.get(node)
                    mesh=scene.geometry[geom_name]
                    if not len(mesh.faces):continue
                    xyz=trimesh.transform_points(mesh.vertices, matrix).astype(np.float32)
                    faces=mesh.faces
                    if len(faces)>3200:
                        stride=max(1,math.ceil(len(faces)/3200));faces=faces[::stride]
                    tris=xyz[faces].reshape(-1,3)
                    mins=np.minimum(mins,tris.min(axis=0));maxs=np.maximum(maxs,tris.max(axis=0));total_tri+=len(faces)
                    normals=mesh.vertex_normals[faces].reshape(-1,3).astype(np.float32)
                    normmat=np.linalg.inv(matrix[:3,:3]).T
                    normals=normals@normmat.T; normals/=np.maximum(np.linalg.norm(normals,axis=1,keepdims=True),1e-6)
                    colors=np.tile(np.array([197,203,210],dtype=np.uint8),(len(tris),1))
                    if pal is not None and getattr(mesh.visual,'uv',None) is not None:
                        uv=mesh.visual.uv[faces].reshape(-1,2);h,w=pal.shape[:2]
                        xx=np.clip(np.round((uv[:,0]%1)*(w-1)).astype('int32'),0,w-1)
                        yy=np.clip(np.round((1-(uv[:,1]%1))*(h-1)).astype('int32'),0,h-1)
                        colors=pal[yy,xx].copy()
                    positions=np.clip(np.round(tris*128),-32767,32767).astype(np.int16)
                    ns=np.clip(np.round(normals*32767),-32767,32767).astype(np.int16)
                    for p,n,c in zip(positions,ns,colors):raw.extend(PACK.pack(*p,*n,int(c[0]),int(c[1]),int(c[2]),45))
                if not raw:continue
                models[key]={'count':len(raw)//16,'data':base64.b64encode(raw).decode('ascii'), 'bounds':[mins.round(3).tolist(),maxs.round(3).tolist()]}
                keys.append(key);count+=1
            except Exception as exc:errors.append((key,str(exc)))
        categories[category]=keys
        print('converted',len(keys),'from',category,flush=True)
output.write_text('/* Kenney CC0 City/Train geometry. Generated by tools/import_kenney_assets.py. */\n'+
 'window.KENNEY_ASSETS='+json.dumps({'version':1,'categories':categories,'models':models},separators=(',',':'))+';\n',encoding='utf-8')
(ROOT/'docs/KENNEY_INVENTORY.json').write_text(json.dumps({'categories':categories,'error':errors,'total':count},indent=2),encoding='utf-8')
print('TOTAL',count,'JS bytes',output.stat().st_size,'failures',errors[:6],flush=True)
